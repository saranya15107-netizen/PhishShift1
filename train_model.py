def build_dataset(data_dir="data"):
    d=Path(data_dir); d.mkdir(parents=True,exist_ok=True); rows=[]
    prefixes=["","Please note: ","Reminder: ","Hello, "]
    for i,(body,label) in enumerate(SAMPLES):
        for j,prefix in enumerate(prefixes):
            text=prefix+body
            rows.append({"message_id":f"msg_{i+1:03d}_{j}","channel":"SMS" if (i+j)%2 else "Email",
             "subject_or_title":"Message notification","body_text":text,
             "sanitized_url_features":"contains_url" if "http" in text else "no_url",
             "sender_domain_type":"unknown" if label=="phishing" else "known_or_unspecified",
             "label":label,"campaign_group":f"campaign_{i+1:03d}",
             "collected_date":"2026-01-01","normalized_template":normalize_template(text)})
    df=pd.DataFrame(rows).drop_duplicates(subset=["body_text","label"]).reset_index(drop=True)
    df.to_csv(d/"synthetic_phishing_dataset.csv",index=False)
    meta={"dataset_name":"PhishShift synthetic educational dataset","source":"Generated by train_model.py; not real-world collected data",
          "rows":len(df),"labels":{str(k):int(v) for k,v in df.label.value_counts().items()},
          "warning":"Demo only. Do not present these metrics as real-world performance."}
    (d/"dataset_metadata.json").write_text(json.dumps(meta,indent=2),encoding="utf-8")
    return df
def train_and_benchmark(output_dir="models",data_dir="data"):
    mdir=Path(output_dir); mdir.mkdir(parents=True,exist_ok=True); df=build_dataset(data_dir)
    X=df.body_text.astype(str); y=df.label.astype(str)
    Xtr,Xte,ytr,yte=train_test_split(X,y,test_size=.25,random_state=42,stratify=y)
    specs={
      "Logistic Regression":Pipeline([("tfidf",TfidfVectorizer(ngram_range=(1,2),max_features=5000)),("classifier",LogisticRegression(max_iter=1000,class_weight="balanced",random_state=42))]),
      "Naive Bayes":Pipeline([("tfidf",TfidfVectorizer(ngram_range=(1,2),max_features=5000)),("classifier",MultinomialNB())])
    }
    metrics={}
    for name,model in specs.items():
        model.fit(Xtr,ytr); pred=model.predict(Xte)
        metrics[name]={"accuracy":float(accuracy_score(yte,pred)),"precision":float(precision_score(yte,pred,pos_label="phishing",zero_division=0)),
        "recall":float(recall_score(yte,pred,pos_label="phishing",zero_division=0)),"f1":float(f1_score(yte,pred,pos_label="phishing",zero_division=0))}
        joblib.dump(model,mdir/("logreg_pipeline.joblib" if name=="Logistic Regression" else "nb_pipeline.joblib"))
    (mdir/"evaluation_metrics.json").write_text(json.dumps(metrics,indent=2),encoding="utf-8")
    (mdir/"campaign_splits.json").write_text(json.dumps({"split_strategy":"stratified random split on synthetic demo data","train_rows":len(Xtr),"test_rows":len(Xte),"limitation":"Not a campaign-separated generalization test."},indent=2),encoding="utf-8")
    return metrics
def ensure_artifacts(data_dir="data",output_dir="models"):
    m=Path(output_dir); needed=[m/"logreg_pipeline.joblib",m/"nb_pipeline.joblib",m/"evaluation_metrics.json"]
    if not all(p.exists() for p in needed): train_and_benchmark(output_dir,data_dir)
    return {"logreg":joblib.load(m/"logreg_pipeline.joblib"),"nb":joblib.load(m/"nb_pipeline.joblib")}
def predict_message(message,models):
    cues=extract_risk_cues(message); probs=[]
    for name,model in [("Logistic Regression",models["logreg"]),("Naive Bayes",models["nb"])]:
        classes=list(model.classes_); p=model.predict_proba([message])[0]; probs.append(float(p[classes.index("phishing")]))
    score=min(1.0,max(0.0,.82*(sum(probs)/len(probs))+min(.18,.04*len(cues))))
    label="PHISHING" if score>=.62 else ("LIKELY LEGITIMATE" if score<=.35 else "REVIEW")
    return {"label":label,"risk_score":score,"model":"Logistic Regression + Naive Bayes","cue_count":len(cues)}
